export const dict = { en, bn };
let lang = 'en';
try {
  lang = localStorage.getItem('tpb_lang') === 'bn' ? 'bn' : 'en';
} catch {}

export function getLang() {
  return lang;
}
export function setLang(l) {
  lang = l === 'bn' ? 'bn' : 'en';
  try {
    localStorage.setItem('tpb_lang', lang);
  } catch {}
  document.documentElement.lang = lang;
}

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
/** Show numbers with Bangla digits in Bangla mode. */
export function num(n) {
  const s = String(n);
  return lang === 'bn' ? s.replace(/\d/g, (d) => BN_DIGITS[d]) : s;
}

export function t(key, vars = {}) {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? (typeof vars[k] === 'number' ? num(vars[k]) : vars[k]) : `{${k}}`));
}

export function reqTitle(r) {
  return lang === 'bn' ? r.title_bn : r.title_en;
}
